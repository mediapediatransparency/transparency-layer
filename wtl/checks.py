def _strings(x):
    if isinstance(x, str):
        yield x
    elif isinstance(x, dict):
        for k, v in x.items():
            if k != "added_by_id":     # pseudonymous account IDs never excuse a name
                yield from _strings(v)
    elif isinstance(x, list):
        for v in x:
            yield from _strings(v)


def public_text(testset: dict) -> str:
    """Text the site shows that never comes from edit histories: the analysed articles' titles
    (listed on the compare page), earlier versions of their own text (data/then_now.json), the
    Wikidata records of cited sources (founders, owners,
    members), and what cited websites say about themselves (home-page titles, self-statements,
    archived titles: the per-site entries of data/siteprobe.json and data/sitetrace.json).
    An account name that is also a word here, e.g. "Edward" in "Edward Said" or in a
    newspaper's founder, is a coincidence, not a leak."""
    parts = [e.get("article", t) for t, e in testset.items()]
    op = ROOT / "data" / "outlets.json"
    if op.exists():
        parts += _strings(json.loads(op.read_text(encoding="utf-8")).get("sources", {}))
    for name in ("siteprobe.json", "sitetrace.json"):
        p = ROOT / "data" / name
        if p.exists():   # only "sites": the groups sections hold pseudonymous account IDs
            parts += _strings(json.loads(p.read_text(encoding="utf-8")).get("sites", {}))
    cp = ROOT / "data" / "categories.json"   # article titles listed on the categories page
    if cp.exists():
        parts += _strings(json.loads(cp.read_text(encoding="utf-8")))
    ap = ROOT / "data" / "authors.json"      # cited authors' Wikipedia titles and Wikidata facts
    if ap.exists():
        a = json.loads(ap.read_text(encoding="utf-8")).get("authors", {})
        parts += list(a) + list(_strings(a))
    tp = ROOT / "data" / "then_now.json"     # earlier versions of the articles' own text
    if tp.exists():
        parts += _strings(json.loads(tp.read_text(encoding="utf-8")).get("articles", {}))
    from .fetch import cache as _cache        # sources on Wikipedia's perennial sources list
    rsp = sorted((_cache.CACHE_DIR / "outlets" / "rsp").glob("*.json.gz"))
    if rsp:
        parts += [r.get("article", "") for r in (_cache.load(rsp[-1]) or {}).get("rows", [])]
    return "\n".join(parts)


URL_IN_DATA = re.compile(r"https?://[^\s\"'<>]+")
SITE_DIR = site_mod.SITE_DIR


LABEL = re.compile(r"Editor \d+")   # the only label form the pages use
_WORDS = {}


def _dictionary() -> set:
    """Single ordinary English words (the system word list, /usr/share/dict/words, if present).
    An account named with one such word ("Neither") matches our own text by coincidence. Without
    the list, no name is excused this way."""
    if "w" not in _WORDS:
        try:
            with open("/usr/share/dict/words", encoding="utf-8") as f:
                _WORDS["w"] = {w.strip().lower() for w in f if w.strip().isalpha() and len(w.strip()) >= 4}
        except OSError:
            _WORDS["w"] = set()
    return _WORDS["w"]


def run_checks(testset: dict):
    results, ok_all = {}, True
    sanction_names = {r["username"] for r in csv.DictReader(open(SANCTIONS_CSV, encoding="utf-8"))}
    public = public_text(testset)
    # every shared page of the site (read once), not only the article's own page
    shared = "\n".join(visible_text(f.read_text(encoding="utf-8"))
                       for f in sorted(SITE_DIR.glob("*.html")))
    for title, e in testset.items():
        d = OUT_DIR / json_writer.slug(e["article"])
        jp = d / f"{e['revision']}.json"
        raw = jp.read_text(encoding="utf-8")
        rec = json.loads(raw)
        a = rec["authorship"]
        res = {}
        # check 2: totals
        words = sum(x["words"] for x in a["editors"])
        lead = sum(x["lead_words"] for x in a["editors"])
        share = sum(x["share"] for x in a["editors"])
        lead_share = sum(x["lead_share"] for x in a["editors"])
        res["totals"] = {
            "editor_words_sum": words, "total_words": a["total_words"],
            "lead_words_sum": lead, "lead_words": a["lead_words"],
            "share_sum": round(share, 6), "lead_share_sum": round(lead_share, 6),
            "pass": words == a["total_words"] and lead == a["lead_words"]
            and abs(share - 1) < 1e-3 and abs(lead_share - 1) < 1e-3,
        }
        # check 6: anonymity — no account name in visible HTML text
        rev = mw.get_revision(rec["revision"])
        names = {h["user"] for h in mw.get_history(rev["pageid"], rec["revision"]) if h.get("user")}
        names |= sanction_names
        text = visible_text((d / f"{e['revision']}.html").read_text(encoding="utf-8"))
        site_page = SITE_DIR / "articles" / f"{json_writer.slug(e['article'])}.html"
        if site_page.exists():   # the public website's page for this article
            text += "\n" + visible_text(site_page.read_text(encoding="utf-8"))
        slug = json_writer.slug(e["article"])   # data files the pages load
        for f in (SITE_DIR / "data" / f"{slug}.json", SITE_DIR / "data" / "editors" / "a" / f"{slug}.js"):
            if f.exists():
                # web addresses are evidence links, where account names may appear
                text += "\n" + URL_IN_DATA.sub(" ", f.read_text(encoding="utf-8"))
        text += "\n" + shared
        article_text = " ".join(s["text"] for s in rec["sentences"])
        # names of the authors this article cites, as its citations give them
        article_text += "\n" + "\n".join(a["name"] for a in (rec.get("sources") or {}).get("authors", []))
        # section headings and the names of cited sources as the article gives them
        article_text += "\n" + "\n".join({x.get("section") or "" for x in rec["sentences"]})
        article_text += "\n" + "\n".join(x.get("name_as_cited") or "" for x in (rec.get("sources") or {}).get("list", []))
        # web addresses of cited websites, as the record lists them ("2016buzz.com")
        article_text += "\n" + "\n".join(set(re.findall(r'"([a-z0-9][a-z0-9.-]*\.[a-z]{2,})"', raw)))
        hits, coincidental, too_short = [], [], 0
        for nm in names:
            if len(nm) < 4:
                too_short += 1
                continue
            if nm not in text:   # plain substring test first: most names are not there at all
                continue
            if LABEL.fullmatch(nm) or nm.lower() in _dictionary():
                coincidental.append(nm)   # our own label form ("Editor 57") or an ordinary English word
                continue
            if nm.isdigit():   # a name made of digits only: not part of a longer number such as 0.00666
                pat = re.compile(r"(?<![\w.,])" + re.escape(nm) + r"(?![\w.,])")
            else:
                pat = re.compile(r"(?<!\w)" + re.escape(nm) + r"(?!\w)")
            if pat.search(text):
                # A name that is also a word of the article's own text or of the report
                # template (e.g. an account called "Editor") is a coincidence, not a leak.
                benign = (pat.search(article_text) or pat.search(TEMPLATE_TEXT)
                          or pat.search(public))
                (coincidental if benign else hits).append(nm)
        res["anonymity"] = {"names_checked": len(names) - too_short,
                            "names_under_4_chars_skipped": too_short,
                            "hits_outside_article_text": len(hits),
                            "coincidental_words_in_article_text": len(coincidental),
                            "pass": not hits}
        # check 5: reproducibility — recompute and compare bytes
        again = json_writer.dumps(pipeline.analyse(revid=rec["revision"],
                                                   area=e.get("topic_area") or ""))
        res["reproducible"] = {"pass": again == raw}
        res["alignment"] = {"unaligned_tokens": rec["quality"]["unaligned_tokens"],
                            "tokens": rec["quality"]["wikiwho_tokens"]}
        ok = all(v.get("pass", True) for v in res.values())
        ok_all &= ok
        results[e["article"]] = res
        print(f"{'PASS' if ok else 'FAIL'}  {e['article']}: totals={res['totals']['pass']} "
              f"anonymity={res['anonymity']['pass']} "
              f"(coincidental words: {len(coincidental)}) reproducible={res['reproducible']['pass']}",
              flush=True)
        if hits:
            print(f"      {len(hits)} account names visible outside article text — review", flush=True)
    (OUT_DIR / "checks.json").write_text(json.dumps(results, indent=1) + "\n", encoding="utf-8")
    return ok_all


class _Diff(HTMLParser):
    """Words a MediaWiki diff inserted and removed.

    A changed line comes as the old and new paragraph side by side, with the actual change wrapped
    in <ins>/<del>; only those parts count. A wholly new or wholly removed line counts in full.
    """
    def __init__(self):
        super().__init__()
        self.new_lines, self.ins, self.gone_lines, self.dels = [], [], [], []
        self._side = None          # "a" or "d" while inside an added/deleted cell
        self._buf, self._mark, self._depth = [], [], 0

    def handle_starttag(self, tag, attrs):
        if tag == "td":
            cls = dict(attrs).get("class", "")
            self._side = ("a" if "diff-addedline" in cls else
                          "d" if "diff-deletedline" in cls else None)
            self._buf, self._mark, self._depth = [], [], 0
        elif self._side and tag in ("ins", "del"):
            self._depth += 1

    def handle_endtag(self, tag):
        if tag == "td" and self._side:
            if self._mark:   # changed line: keep only the highlighted change
                (self.ins if self._side == "a" else self.dels).append(" ".join(self._mark))
            else:            # wholly new or wholly removed line
                (self.new_lines if self._side == "a" else self.gone_lines).append(" ".join(self._buf))
            self._side = None
        elif self._side and tag in ("ins", "del") and self._depth:
            self._depth -= 1

    def handle_data(self, data):
        if self._side:
            self._buf.append(data)
            if self._depth:
                self._mark.append(data)


# ---------------------------------------------------------------- check 1: hand-check helper
def inserted_words(revid: int) -> Counter:
    """Words this revision inserted. A wholly new line that closely matches a wholly removed one
    is a moved paragraph and is skipped, so moving text does not count as writing it. (Netting all
    removed words against all new ones would wrongly cancel new text in edits that also delete
    a section.)"""
    c = mw.compare(revid)
    p = _Diff()
    p.feed(c.get("body", ""))
    words = lambda parts: Counter(re.findall(r"\w+", " ".join(parts).lower()))
    gone = [words([g]) for g in p.gone_lines]
    out = words(p.ins)
    for line in p.new_lines:
        w = words([line])
        size = sum(w.values())
        moved = size and any(sum((w & g).values()) >= 0.9 * max(size, sum(g.values())) for g in gone)
        if not moved:
            out += w
    return out, c


def spotcheck(testset: dict, n: int = 20, seed: int = 1):
    pool = []
    recs = {}
    for t, e in testset.items():
        rec = json.loads((OUT_DIR / json_writer.slug(e["article"]) /
                          f"{e['revision']}.json").read_text(encoding="utf-8"))
        recs[e["article"]] = (rec, e)
        pool += [(e["article"], s) for s in rec["sentences"] if s["words"] >= 6]
    pool.sort(key=lambda x: (x[0], x[1]["id"]))
    sample = random.Random(seed).sample(pool, n)
    rows, passed = [], 0
    internals = {}
    for art, s in sample:
        rec, e = recs[art]
        if art not in internals:
            internals[art] = pipeline.analyse(revid=rec["revision"], area=e.get("topic_area") or "",
                                              internals=True)[1]
        labels = internals[art]["labels"]
        r = s["added_revision"]
        new, cmp = inserted_words(r)
        expected = s["revision_words"][0] / s["words"]
        sw = re.findall(r"\w+", s["text"].lower())
        pool_new, found = Counter(new), 0
        for wd in sw:
            if pool_new[wd] > 0:
                pool_new[wd] -= 1
                found += 1
        frac = found / len(sw) if sw else 0
        uid = cmp.get("touserid")
        key = f"u{uid}" if uid else f"n:{cmp.get('touser')}"
        rev_label = labels.get(key, "(editor has no surviving words)")
        same_editor = rev_label == s["authors"][0]
        ok = same_editor and frac >= expected - 0.15
        passed += ok
        rows.append((art, s, r, expected, frac, rev_label, same_editor, ok))
    lines = ["# Authorship hand-check", "",
             f"Generated by `python -m wtl spotcheck --n {n} --seed {seed}`: {n} random sentences "
             "(6+ words) across the test set. For each, the revision credited with most of the "
             "sentence's words is opened as a diff against its parent, and the script counts how "
             "many of the sentence's words that diff inserted. *Expected* is the share of the "
             "sentence WikiWho credits to that revision. The row passes if the account that saved "
             "the revision is the credited author *and* the diff inserts at least that share, less "
             "15 points (tokenisation differs slightly). *Editor of revision* is the label of the "
             "account that saved it. Moved paragraphs are not counted as inserted.", "",
             f"**{passed} of {n} pass.**", "",
             "| # | Article | Sentence | Credited author | Revision | Editor of revision | "
             "Expected | Found in diff | Pass |", "|---|---|---|---|---|---|---|---|---|"]
    for i, (art, s, r, exp, frac, lab, same, ok) in enumerate(rows, 1):
        text = s["text"] if len(s["text"]) < 140 else s["text"][:137] + "…"
        text = text.replace("|", "\\|")
        lines.append(f"| {i} | {art} | {s['id']}: {text} | {s['authors'][0]} | "
                     f"[{r}](https://en.wikipedia.org/w/index.php?diff=prev&oldid={r}) | "
                     f"{lab}{'' if same else ' (differs)'} | {exp:.0%} | {frac:.0%} | "
                     f"{'yes' if ok else '**no**'} |")
    (DOCS / "spotcheck.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{passed}/{n} pass; report in {DOCS / 'spotcheck.md'}")
