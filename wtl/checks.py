def acct_note(acct: dict) -> str:
    if acct.get("rename_logids"):
        logs = ", ".join(f"[log {i}](https://en.wikipedia.org/w/index.php?title=Special:Log&logid={i})"
                         for i in acct["rename_logids"])
        return f"yes, renamed ({logs})"
    return "yes" if acct.get("userid") else "**no**"


def verify_sanctions(path=SANCTIONS_CSV):
    rows = list(csv.DictReader(open(path, newline="", encoding="utf-8")))
    ids = mw.resolve_users(sorted({r["username"] for r in rows}))
    out, problems = [], 0
    for n, r in enumerate(rows, start=2):
        m = re.search(r"[?&]oldid=(\d+)", r["decision_url"])
        page = mw.page_wikitext(int(m.group(1))) if m else None
        w = page["wikitext"] if page else ""
        found = bool(page) and r["source_quote"] in w
        named = r["username"] in r["source_quote"]
        date_ok = False
        if found:
            i = w.find(r["source_quote"])
            line_end = w.find("\n", i + len(r["source_quote"]))
            line = w[w.rfind("\n", 0, i) + 1: line_end if line_end > 0 else None]
            # AE log entries carry their date in the signature on the same line; ArbCom
            # notices carry it in the vote line or signature that follows the motion text.
            dates = [_iso(x) for x in SIG.finditer(line)]
            if r["date"] not in dates:
                dates += [_iso(x) for x in SIG.finditer(w[i:i + 6000])]
            date_ok = r["date"] in dates
        acct = ids[r["username"]]
        exists = bool(acct.get("userid"))
        ok = found and named and date_ok
        problems += not ok
        out.append((n, r, found, named, date_ok, exists))

    lines = ["# Sanctions seed list: verification", "",
             f"Generated by `python -m wtl verify-sanctions` from `data/sanctions.csv` "
             f"({len(rows)} rows).", "",
             "For each row the script opens the permalinked revision in `decision_url`, confirms "
             "that `source_quote` appears there verbatim, that the quote names the account, and "
             "that the row's date matches the entry's signature or the motion's vote line. It also "
             "checks that the account exists; renamed accounts are followed through Wikipedia's "
             "rename log to the current account, with the log entry linked.", "",
             f"**Result: {len(rows) - problems} of {len(rows)} rows confirmed; "
             f"{sum(1 for o in out if not o[5])} accounts not found, "
             f"{sum(1 for o in out if ids[o[1]['username']].get('rename_logids'))} rows matched "
             f"through Wikipedia's rename log.**", "",
             "| CSV line | Area | Type | Date | Authority | Quote found | Names account | "
             "Date confirmed | Account exists |", "|---|---|---|---|---|---|---|---|---|"]
    yes = {True: "yes", False: "**NO**"}
    for n, r, found, named, date_ok, exists in out:
        lines.append(f"| {n} | {r['area']} | {r['sanction_type']} | {r['date']} | "
                     f"{r['authority']} | {yes[found]} | {yes[named]} | {yes[date_ok]} | "
                     f"{acct_note(ids[r['username']])} |")
    lines += ["", "## Both sides", "",
              "The seed list includes sanctions that the Arbitration Committee itself tied to "
              "campaigns pushing opposite points of view, quoted from the linked decisions:", "",
              "- 20 January 2024 motion: an effort by banned editors “to canvass discussions "
              "within the Israel-Palestine topic area and asking for proxy edits to promote a "
              "pro-Israel point of view”, leading to site bans and topic bans for three accounts "
              "(rows dated 2024-01-20).",
              "- 9 December 2024 and 26 April 2025 notices: off-wiki canvassing including the "
              "“Tech4Palestine” Discord server, leading to site bans and topic bans for four "
              "accounts (rows dated 2024-12-09 and 2025-04-26).",
              "- 23 January 2025 PIA5 decision: indefinite topic bans for eight editors, "
              "reported in the press as covering editors from both camps.", "",
              "The code never uses these labels: no column records a side, and every rule applies "
              "to every row the same way."]
    DOCS.mkdir(exist_ok=True)
    (DOCS / "sanctions-verification.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(rows) - problems}/{len(rows)} rows confirmed; report in "
          f"{DOCS / 'sanctions-verification.md'}")
    for n, r, found, named, date_ok, exists in out:
        if not (found and named and date_ok):
            print(f"  line {n}: quote={found} names={named} date={date_ok}")
    return problems == 0


# ---------------------------------------------------------------- checks 2, 5, 6
_BLOCK = {"p", "div", "br", "li", "ul", "ol", "tr", "td", "th", "table", "thead", "tbody",
          "h1", "h2", "h3", "h4", "h5", "h6", "section", "header", "footer", "nav", "details",
          "summary", "dt", "dd", "dl", "caption", "figcaption", "blockquote", "pre", "option",
          "label", "select", "button", "title"}


class _Visible(HTMLParser):
    """Collect visible text (never attribute values such as href).

    Text inside one line is kept exactly as a reader sees it ("Foo <i>Bar</i>" -> "Foo Bar"), so a
    name split by inline markup is still found; block and table-cell boundaries become line
    breaks, so two neighbouring cells ("C. L. R. James" | "4,983") never read as one name."""

    def __init__(self):
        super().__init__()
        self.parts, self._skip = [], 0

    def handle_starttag(self, tag, attrs):
        if tag in ("style", "script"):
            self._skip += 1
        elif tag in _BLOCK:
            self.parts.append("\n")

    def handle_endtag(self, tag):
        if tag in ("style", "script"):
            self._skip -= 1
        elif tag in _BLOCK:
            self.parts.append("\n")

    def handle_data(self, data):
        if not self._skip:
            self.parts.append(data)


def visible_text(html: str) -> str:
    p = _Visible()
    p.feed(html)
    return "".join(p.parts)


