DOCS = ROOT / "docs"
SIG = re.compile(r"(\d{1,2}) (January|February|March|April|May|June|July|August|September|"
                 r"October|November|December) (\d{4})")
MONTHS = {m: i for i, m in enumerate(["January", "February", "March", "April", "May", "June",
                                      "July", "August", "September", "October", "November",
                                      "December"], start=1)}


def _iso(m):
    return f"{m.group(3)}-{MONTHS[m.group(2)]:02d}-{int(m.group(1)):02d}"


# ---------------------------------------------------------------- check 3: sanctions list
def acct_note(acct: dict) -> str:
    if acct.get("rename_logids"):
        logs = ", ".join(f"[log {i}](https://en.wikipedia.org/w/index.php?title=Special:Log&logid={i})"
                         for i in acct["rename_logids"])
        return f"yes, renamed ({logs})"
    return "yes" if acct.get("userid") else "**no**"


def verify_sanctions(path=SANCTIONS_CSV):
    rows = list(csv.DictReader(open(path, newline="", encoding="utf-8")))
    ids = mw.resolve_users(sorted({r["username"] for r in rows}))
    out, problems = [], 0
    for n, r in enumerate(rows, start=2):
        m = re.search(r"[?&]oldid=(\d+)", r["decision_url"])
        page = mw.page_wikitext(int(m.group(1))) if m else None
        w = page["wikitext"] if page else ""
        found = bool(page) and r["source_quote"] in w
        named = r["username"] in r["source_quote"]
        date_ok = False
        if found:
            i = w.find(r["source_quote"])
            line_end = w.find("\n", i + len(r["source_quote"]))
            line = w[w.rfind("\n", 0, i) + 1: line_end if line_end > 0 else None]
            # AE log entries carry their date in the signature on the same line; ArbCom
            # notices carry it in the vote line or signature that follows the motion text.
            dates = [_iso(x) for x in SIG.finditer(line)]
            if r["date"] not in dates:
                dates += [_iso(x) for x in SIG.finditer(w[i:i + 6000])]
            date_ok = r["date"] in dates
        acct = ids[r["username"]]
        exists = bool(acct.get("userid"))
        ok = found and named and date_ok
        problems += not ok
        out.append((n, r, found, named, date_ok, exists))

    lines = ["# Sanctions seed list: verification", "",
             f"Generated by `python -m wtl verify-sanctions` from `data/sanctions.csv` "
             f"({len(rows)} rows).", "",
             "For each row the script opens the permalinked revision in `decision_url`, confirms "
             "that `source_quote` appears there verbatim, that the quote names the account, and "
             "that the row's date matches the entry's signature or the motion's vote line. It also "
             "checks that the account exists; renamed accounts are followed through Wikipedia's "
             "rename log to the current account, with the log entry linked.", "",
             f"**Result: {len(rows) - problems} of {len(rows)} rows confirmed; "
             f"{sum(1 for o in out if not o[5])} accounts not found, "
             f"{sum(1 for o in out if ids[o[1]['username']].get('rename_logids'))} rows matched "
             f"through Wikipedia's rename log.**", "",
             "| CSV line | Area | Type | Date | Authority | Quote found | Names account | "
             "Date confirmed | Account exists |", "|---|---|---|---|---|---|---|---|---|"]
    yes = {True: "yes", False: "**NO**"}
    for n, r, found, named, date_ok, exists in out:
        lines.append(f"| {n} | {r['area']} | {r['sanction_type']} | {r['date']} | "
                     f"{r['authority']} | {yes[found]} | {yes[named]} | {yes[date_ok]} | "
                     f"{acct_note(ids[r['username']])} |")
    lines += ["", "## Both sides", "",
              "The seed list includes sanctions that the Arbitration Committee itself tied to "
              "campaigns pushing opposite points of view, quoted from the linked decisions:", "",
              "- 20 January 2024 motion: an effort by banned editors “to canvass discussions "
              "within the Israel-Palestine topic area and asking for proxy edits to promote a "
              "pro-Israel point of view”, leading to site bans and topic bans for three accounts "
              "(rows dated 2024-01-20).",
              "- 9 December 2024 and 26 April 2025 notices: off-wiki canvassing including the "
              "“Tech4Palestine” Discord server, leading to site bans and topic bans for four "
              "accounts (rows dated 2024-12-09 and 2025-04-26).",
              "- 23 January 2025 PIA5 decision: indefinite topic bans for eight editors, "
              "reported in the press as covering editors from both camps.", "",
              "The code never uses these labels: no column records a side, and every rule applies "
              "to every row the same way."]
    DOCS.mkdir(exist_ok=True)
    (DOCS / "sanctions-verification.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(rows) - problems}/{len(rows)} rows confirmed; report in "
          f"{DOCS / 'sanctions-verification.md'}")
    for n, r, found, named, date_ok, exists in out:
        if not (found and named and date_ok):
            print(f"  line {n}: quote={found} names={named} date={date_ok}")
    return problems == 0


# ---------------------------------------------------------------- checks 2, 5, 6
class _Visible(HTMLParser):
    """Collect visible text (never attribute values such as href)."""

    def __init__(self):
        super().__init__()
        self.parts, self._skip = [], 0

    def handle_starttag(self, tag, attrs):
        if tag in ("style", "script"):
            self._skip += 1

    def handle_endtag(self, tag):
        if tag in ("style", "script"):
            self._skip -= 1

    def handle_data(self, data):
        if not self._skip:
            self.parts.append(data)


def visible_text(html: str) -> str:
    p = _Visible()
    p.feed(html)
    return " ".join(p.parts)


TEMPLATE_TEXT = open(html_mod.__file__, encoding="utf-8").read()


def run_checks(testset: dict):
    results, ok_all = {}, True
    sanction_names = {r["username"] for r in csv.DictReader(open(SANCTIONS_CSV, encoding="utf-8"))}
    for title, e in testset.items():
        d = OUT_DIR / json_writer.slug(e["article"])
        jp = d / f"{e['revision']}.json"
        raw = jp.read_text(encoding="utf-8")
        rec = json.loads(raw)
        a = rec["authorship"]
        res = {}
        # check 2: totals
        words = sum(x["words"] for x in a["editors"])
        lead = sum(x["lead_words"] for x in a["editors"])
        share = sum(x["share"] for x in a["editors"])
        lead_share = sum(x["lead_share"] for x in a["editors"])
        res["totals"] = {
            "editor_words_sum": words, "total_words": a["total_words"],
            "lead_words_sum": lead, "lead_words": a["lead_words"],
            "share_sum": round(share, 6), "lead_share_sum": round(lead_share, 6),
            "pass": words == a["total_words"] and lead == a["lead_words"]
            and abs(share - 1) < 1e-3 and abs(lead_share - 1) < 1e-3,
        }
        # check 6: anonymity — no account name in visible HTML text
        rev = mw.get_revision(rec["revision"])
        names = {h["user"] for h in mw.get_history(rev["pageid"], rec["revision"]) if h.get("user")}
        names |= sanction_names
        text = visible_text((d / f"{e['revision']}.html").read_text(encoding="utf-8"))
        article_text = " ".join(s["text"] for s in rec["sentences"])
        hits, coincidental, too_short = [], [], 0
        for nm in names:
            if len(nm) < 4:
                too_short += 1
                continue
            pat = re.compile(r"(?<!\w)" + re.escape(nm) + r"(?!\w)")
            if pat.search(text):
                # A name that is also a word of the article's own text or of the report
                # template (e.g. an account called "Editor") is a coincidence, not a leak.
                benign = pat.search(article_text) or pat.search(TEMPLATE_TEXT)
                (coincidental if benign else hits).append(nm)
        res["anonymity"] = {"names_checked": len(names) - too_short,
                            "names_under_4_chars_skipped": too_short,
                            "hits_outside_article_text": len(hits),
                            "coincidental_words_in_article_text": len(coincidental),
                            "pass": not hits}
        # check 5: reproducibility — recompute and compare bytes
        again = json_writer.dumps(pipeline.analyse(revid=rec["revision"],
                                                   area=e.get("topic_area") or ""))
        res["reproducible"] = {"pass": again == raw}
        res["alignment"] = {"unaligned_tokens": rec["quality"]["unaligned_tokens"],
                            "tokens": rec["quality"]["wikiwho_tokens"]}
        ok = all(v.get("pass", True) for v in res.values())
        ok_all &= ok
        results[e["article"]] = res
        print(f"{'PASS' if ok else 'FAIL'}  {e['article']}: totals={res['totals']['pass']} "
              f"anonymity={res['anonymity']['pass']} "
              f"(coincidental words: {len(coincidental)}) reproducible={res['reproducible']['pass']}")
        if hits:
            print(f"      {len(hits)} account names visible outside article text — review")
    (OUT_DIR / "checks.json").write_text(json.dumps(results, indent=1) + "\n", encoding="utf-8")
    return ok_all


# ---------------------------------------------------------------- check 1: hand-check helper
class _Diff(HTMLParser):
    def __init__(self):
        super().__init__()
        self.added, self.deleted, self._cell = [], [], []

    def handle_starttag(self, tag, attrs):
        if tag == "td":
            cls = dict(attrs).get("class", "")
            self._cell.append("a" if "diff-addedline" in cls else
                              "d" if "diff-deletedline" in cls else "")

    def handle_endtag(self, tag):
        if tag == "td" and self._cell:
            self._cell.pop()

    def handle_data(self, data):
        if self._cell and self._cell[-1] == "a":
            self.added.append(data)
        elif self._cell and self._cell[-1] == "d":
            self.deleted.append(data)


def inserted_words(revid: int) -> Counter:
    c = mw.compare(revid)
    p = _Diff()
    p.feed(c.get("body", ""))
    words = lambda parts: Counter(re.findall(r"\w+", " ".join(parts).lower()))
    return words(p.added) - words(p.deleted), c


def spotcheck(testset: dict, n: int = 20, seed: int = 1):
    pool = []
    recs = {}
    for t, e in testset.items():
        rec = json.loads((OUT_DIR / json_writer.slug(e["article"]) /
                          f"{e['revision']}.json").read_text(encoding="utf-8"))
        recs[e["article"]] = (rec, e)
        pool += [(e["article"], s) for s in rec["sentences"] if s["words"] >= 6]
    pool.sort(key=lambda x: (x[0], x[1]["id"]))
    sample = random.Random(seed).sample(pool, n)
    rows, passed = [], 0
    internals = {}
    for art, s in sample:
        rec, e = recs[art]
        if art not in internals:
            internals[art] = pipeline.analyse(revid=rec["revision"], area=e.get("topic_area") or "",
                                              internals=True)[1]
        labels = internals[art]["labels"]
        r = s["added_revision"]
        new, cmp = inserted_words(r)
        expected = s["revision_words"][0] / s["words"]
        sw = re.findall(r"\w+", s["text"].lower())
        pool_new, found = Counter(new), 0
        for wd in sw:
            if pool_new[wd] > 0:
                pool_new[wd] -= 1
                found += 1
        frac = found / len(sw) if sw else 0
        uid = cmp.get("touserid")
        key = f"u{uid}" if uid else f"n:{cmp.get('touser')}"
        rev_label = labels.get(key, "(editor has no surviving words)")
        same_editor = rev_label == s["authors"][0]
        ok = frac >= expected - 0.15
        passed += ok
        rows.append((art, s, r, expected, frac, rev_label, same_editor, ok))
    lines = ["# Authorship hand-check", "",
             f"Generated by `python -m wtl spotcheck --n {n} --seed {seed}`: {n} random sentences "
             "(6+ words) across the test set. For each, the revision credited with most of the "
             "sentence's words is opened as a diff against its parent, and the script counts how "
             "many of the sentence's words that diff inserted. *Expected* is the share of the "
             "sentence WikiWho credits to that revision; the row passes if the diff inserts at "
             "least that share, less 15 points (tokenisation differs slightly). *Editor of revision* "
             "is the label of the account that saved it.", "",
             f"**{passed} of {n} pass.**", "",
             "| # | Article | Sentence | Credited author | Revision | Editor of revision | "
             "Expected | Found in diff | Pass |", "|---|---|---|---|---|---|---|---|---|"]
    for i, (art, s, r, exp, frac, lab, same, ok) in enumerate(rows, 1):
        text = s["text"] if len(s["text"]) < 140 else s["text"][:137] + "…"
        text = text.replace("|", "\\|")
        lines.append(f"| {i} | {art} | {s['id']}: {text} | {s['authors'][0]} | "
                     f"[{r}](https://en.wikipedia.org/w/index.php?diff=prev&oldid={r}) | "
                     f"{lab}{'' if same else ' (differs)'} | {exp:.0%} | {frac:.0%} | "
                     f"{'yes' if ok else '**no**'} |")
    (DOCS / "spotcheck.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{passed}/{n} pass; report in {DOCS / 'spotcheck.md'}")
